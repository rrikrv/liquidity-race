"""
Export synthetic data in the format participant 1 asked for.

    team_data/daily.csv.gz        stock-day panel, CRSP column names
    team_data/stock_month.csv     true_spread (+ realized spread, price impact) per stock-month
    team_data/trades.csv.gz       intraday trades  (permno, ts, price, size, side)
    team_data/quotes.csv.gz       intraday quotes  (permno, ts, bid, ask), one row per change
    team_data/stocks.csv          true per-stock parameters
    team_data/DATA_README.md      column dictionary

Run from the participant2 folder:
    python scripts/export_for_team.py                         # defaults below, ~1 min
    python scripts/export_for_team.py --stocks 400 --months 60 --intraday-stocks 100 --intraday-months 12

If participant 1's panel uses other column names, change RENAME_DAILY only.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from intraday_sim import simulate_intraday, truth_from_trades
from liquidity_sim import SimConfig, benchmark, simulate

RENAME_DAILY = {
    "stock": "permno",
    "date": "date",
    "prc": "prc",
    "volume": "vol",
    "ret": "ret",
    "bid": "bid",
    "ask": "ask",
    "mkt_ret": "vwretd",
}

ap = argparse.ArgumentParser()
ap.add_argument("--stocks", type=int, default=400)
ap.add_argument("--months", type=int, default=60)
ap.add_argument("--start", default="1993-01")
ap.add_argument("--grid", default="eighths", choices=["eighths", "sixteenths", "decimal"])
ap.add_argument("--cluster-strength", type=float, default=1.0)
ap.add_argument("--intraday-stocks", type=int, default=100, help="0 = no intraday data")
ap.add_argument("--intraday-months", type=int, default=12)
ap.add_argument("--seed", type=int, default=1)
ap.add_argument("--out", default=str(ROOT / "team_data"))
a = ap.parse_args()
out = Path(a.out)
out.mkdir(parents=True, exist_ok=True)

cfg = SimConfig(n_stocks=a.stocks, n_months=a.months, grid=a.grid,
                cluster_strength=a.cluster_strength, calendar_start=a.start, seed=a.seed)
print(f"daily panel: {a.stocks} stocks x {a.months} months from {a.start} ...")
daily, stocks = simulate(cfg)
daily["yyyymm"] = daily["date"].dt.year * 100 + daily["date"].dt.month

d = daily.copy()
d["prc"] = np.where(d["traded"], d["price"], -d["mid"])
cols = list(RENAME_DAILY)
d[cols].rename(columns=RENAME_DAILY).to_csv(out / "daily.csv.gz", index=False, float_format="%.10g")

ym = daily.groupby("month")["yyyymm"].first()
sm = benchmark(daily).rename("true_spread_close").reset_index().rename(columns={"win": "month"})
sm["yyyymm"] = sm["month"].map(ym)
target = pd.DataFrame(daily.attrs["target"].array).stack().rename("target_spread").reset_index()
target.columns = ["month", "stock", "target_spread"]
sm = sm.merge(target, on=["month", "stock"])
sm = sm.merge(daily.groupby(["stock", "month"])["traded"].sum().rename("n_trade_days").reset_index(),
              on=["stock", "month"])

if a.intraday_stocks > 0:
    ids = list(range(min(a.intraday_stocks, a.stocks)))
    months = list(range(min(a.intraday_months, a.months)))
    print(f"intraday: {len(ids)} stocks x {len(months)} months ...")
    trades, quotes = simulate_intraday(daily, stocks, stock_ids=ids, months=months, seed=a.seed + 1000)
    truth = truth_from_trades(trades, quotes).reset_index()
    sm = sm.merge(truth, on=["stock", "yyyymm"], how="left")
    trades.rename(columns={"stock": "permno"}).to_csv(out / "trades.csv.gz", index=False,
                                                      float_format="%.10g", date_format="%Y-%m-%d %H:%M:%S")
    quotes.rename(columns={"stock": "permno"}).to_csv(out / "quotes.csv.gz", index=False,
                                                      float_format="%.10g", date_format="%Y-%m-%d %H:%M:%S")
    print(f"  {len(trades):,} trades, {len(quotes):,} quote changes")
else:
    for c in ["true_eff_spread", "true_realized_spread", "true_price_impact_5min", "n_trades"]:
        sm[c] = np.nan

has = sm["true_eff_spread"].notna()
sm["true_spread"] = np.where(has, sm["true_eff_spread"], sm["true_spread_close"])
sm["true_spread_source"] = np.where(has, "intraday", "close")
sm = sm.rename(columns={"stock": "permno"})
sm = sm[["permno", "yyyymm", "true_spread", "true_spread_source", "true_spread_close",
         "true_eff_spread", "true_realized_spread", "true_price_impact_5min", "n_trades",
         "n_trade_days", "target_spread"]].sort_values(["permno", "yyyymm"])
sm.to_csv(out / "stock_month.csv", index=False, float_format="%.10g")
stocks.rename_axis("permno").to_csv(out / "stocks.csv", float_format="%.10g")

(out / "DATA_README.md").write_text(f"""# Synthetic data for the team (participant 2)

Generated by `scripts/export_for_team.py`: {a.stocks} stocks x {a.months} months from {a.start},
grid `{a.grid}`, cluster strength {a.cluster_strength}, seed {a.seed}.
Intraday data: first {min(a.intraday_stocks, a.stocks)} permnos, first {min(a.intraday_months, a.months)} months.
Dates are weekdays (no exchange holidays).

## daily.csv.gz (one row per permno-date)
| column | meaning |
|---|---|
| permno | stock id (0..N-1) |
| date | trading day |
| prc | closing price; negative = bid/ask midpoint on a day without trades (CRSP convention, use abs) |
| vol | shares traded (0 = no trade) |
| ret | daily return from abs(prc) |
| bid, ask | closing quote |
| vwretd | market return |

## stock_month.csv (one row per permno-month)
| column | meaning |
|---|---|
| true_spread | THE benchmark to compare with: dollar-volume-weighted 2abs(ln P - ln M) over all simulated trades of the month |
| true_spread_source | `intraday` (all intraday trades) or `close` (only closing trades: no intraday data for this stock-month) |
| true_spread_close | the same over closing trades only (used on participant 2's slides) |
| true_eff_spread | intraday effective spread, eq. (1); equals true_spread when source = intraday |
| true_realized_spread | 2 Q (ln P - ln M 5 min later), the Huang-Stoll midpoint variant, NOT the paper's eq. (2), which uses the trade price 5 min later (corr between the two: 0.92); TRUE side |
| true_price_impact_5min | 2 Q (ln M 5 min later - ln M), eq. (6), with the TRUE side |
| n_trades | intraday trades in the month |
| n_trade_days | days with volume > 0 |
| target_spread | the model parameter s_i,m (spread the simulator aimed at) |

Your benchmarks.py on trades + quotes should reproduce `true_eff_spread` exactly (it needs no trade side).
For realized spread and price impact, the gap between your Lee-Ready numbers and the `true_` ones is the
classification error: 10% of trades execute at the midpoint, so the tick test is needed for them.

## trades.csv.gz
permno, ts, price, size (shares), side (+1 buy, -1 sell; the true side, ignore it to test Lee-Ready).
The last trade of each day at 15:59:59 is the daily close (same price as daily prc).

## quotes.csv.gz
permno, ts, bid, ask: one row at 09:30 and one each time the quote changes (minute resolution);
the 15:59:00 row is the daily closing quote.
""")
print("written to", out)
print(sm.describe().round(4).to_string())
